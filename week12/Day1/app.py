load_dotenv()

# ── Required keys ─────────────────────────────────────────────────────────────
GROQ_API_KEY   = os.getenv("GROQ_API_KEY", "")
TAVILY_API_KEY = os.getenv("TAVILY_API_KEY", "")

# ── Optional keys ─────────────────────────────────────────────────────────────
GOOGLE_API_KEY  = os.getenv("GOOGLE_API_KEY", "")
LANGCHAIN_API_KEY = os.getenv("LANGCHAIN_API_KEY", "")

# ── LangSmith tracing (enabled when LANGCHAIN_API_KEY is present) ─────────────
if LANGCHAIN_API_KEY:
    os.environ["LANGCHAIN_TRACING_V2"]  = "true"
    os.environ["LANGCHAIN_API_KEY"]     = LANGCHAIN_API_KEY
    os.environ["LANGCHAIN_ENDPOINT"]    = "https://api.smith.langchain.com"
    os.environ["LANGCHAIN_PROJECT"]     = os.getenv("LANGCHAIN_PROJECT", "agentic-rag")
else:
    os.environ["LANGCHAIN_TRACING_V2"] = "false"

# ── Push remaining keys into env so LangChain picks them up ───────────────────
if GROQ_API_KEY:
    os.environ["GROQ_API_KEY"] = GROQ_API_KEY
if TAVILY_API_KEY:
    os.environ["TAVILY_API_KEY"] = TAVILY_API_KEY
if GOOGLE_API_KEY:
    os.environ["GOOGLE_API_KEY"] = GOOGLE_API_KEY

# ── Streamlit ──────────────────────────────────────────────────────────────────
import streamlit as st

# ── Attempt to import the agent from the notebook-extracted module ─────────────
AGENT_AVAILABLE = False
agent_run = None
NOTEBOOK_PATH = pathlib.Path("agentic_rag.ipynb")

try:
    # Load notebook source for display
    if NOTEBOOK_PATH.exists():
        nb_text = NOTEBOOK_PATH.read_text(encoding="utf-8")
        nb_json = json.loads(nb_text)
    else:
        nb_json = None

    # Try importing the compiled agent module (generated by the notebook)
    import importlib, sys
    if pathlib.Path("agentic_rag_agent.py").exists():
        spec = importlib.util.spec_from_file_location("agentic_rag_agent",
                                                        "agentic_rag_agent.py")
        mod  = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        agent_run      = mod.agent_run       # expected public function
        AGENT_AVAILABLE = True
except Exception as exc:
    agent_run = None
    _import_error = str(exc)


