# ── Session state ─────────────────────────────────────────────────────────────
if "history" not in st.session_state:
    st.session_state.history = []   # list of {query, answer, sources, steps, elapsed}

# ── Query input ───────────────────────────────────────────────────────────────
query = st.text_area(
    "Ask anything — the agent will retrieve, reason, and synthesize an answer:",
    height=90,
    placeholder="e.g. What are the latest advances in multimodal LLMs?",
    key="query_input",
)

col_submit, col_clear, col_spacer = st.columns([1, 1, 6])
with col_submit:
    submitted = st.button("🚀 Submit", use_container_width=True)
with col_clear:
    if st.button("🗑 Clear", use_container_width=True):
        st.session_state.history = []
        st.rerun()

# =============================================================================
# AGENT CALL (or simulation)
# =============================================================================
if submitted and query.strip():
    with st.spinner("Agent is thinking…"):
        t0 = time.time()

        if AGENT_AVAILABLE and agent_run:
            # ── Real agent call ────────────────────────────────────────────
            try:
                result = agent_run(
                    query=query,
                    model_name=model_name,
                    max_iterations=max_iterations,
                    use_web_search=use_web_search,
                )
                answer  = result.get("answer", "No answer returned.")
                sources = result.get("sources", [])
                steps   = result.get("steps",  [])
            except Exception as exc:
                answer  = f"⚠️ Agent error: {exc}"
                sources = []
                steps   = [{"icon": "❌", "text": str(exc)}]

        else:
            # ── Simulated response (notebook not yet compiled) ─────────────
            time.sleep(1.2)   # simulate latency
            answer = textwrap.dedent(f"""
                **[Simulated answer — connect the real agent in `agentic_rag.ipynb`]**

                Your query was: *"{query}"*

                The agentic RAG pipeline would:
                1. Embed the query and search the vector store (ChromaDB / FAISS).
                2. Call Tavily web search if the retriever score is below threshold.
                3. Pass retrieved context + the original query to the Groq LLM
                   (`{model_name}`) for synthesis.
                4. Return a grounded answer with source attribution.

                Once you export `agent_run()` from the notebook into
                `agentic_rag_agent.py`, this placeholder disappears automatically.
            """).strip()
            sources = [
                {"title": "ChromaDB docs", "url": "https://docs.trychroma.com"},
                {"title": "Tavily API",     "url": "https://docs.tavily.com"},
                {"title": "Groq Cloud",     "url": "https://console.groq.com/docs"},
            ]
            steps = [
                {"icon": "🔎", "text": "Query embedded with HuggingFace sentence-transformer"},
                {"icon": "📚", "text": "Vector store searched — top-3 chunks retrieved"},
                {"icon": "🌐", "text": "Tavily web search called (score below threshold)"},
                {"icon": "🧠", "text": f"Groq `{model_name}` synthesised answer"},
                {"icon": "✅", "text": "Sources attributed"},
            ]

        elapsed = time.time() - t0

    st.session_state.history.insert(0, {
        "query":   query,
        "answer":  answer,
        "sources": sources,
        "steps":   steps,
        "elapsed": elapsed,
    })

# =============================================================================
# DISPLAY HISTORY
# =============================================================================
for i, item in enumerate(st.session_state.history):
    with st.container():
        st.markdown(f"**Q:** {item['query']}")

        # Answer card
        st.markdown(
            f'<div class="answer-card">{item["answer"]}</div>',
            unsafe_allow_html=True,
        )

        # Sources
        if item["sources"]:
            src_html = " ".join(
                f'<a class="source-tag" href="{s.get("url","#")}" target="_blank">'
                f'🔗 {s.get("title", s.get("url","source"))}</a>'
                for s in item["sources"]
            )
            st.markdown(src_html, unsafe_allow_html=True)

        # Reasoning steps (collapsible)
        if item["steps"]:
            with st.expander(f"🔬 Reasoning trace  •  {item['elapsed']:.1f}s", expanded=(i==0)):
                for step in item["steps"]:
                    icon = step.get("icon", "•")
                    text = step.get("text", "")
                    st.markdown(
                        f'<div class="step-row">'
                        f'<span class="step-icon">{icon}</span>'
                        f'<span class="step-text">{text}</span>'
                        f'</div>',
                        unsafe_allow_html=True,
                    )

        st.divider()

